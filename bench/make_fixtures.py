"""Extract real Stage 2 inputs from real footage.

Benchmarking or evaluating a VLM on stock photos measures the wrong thing.
Stage 2 never sees a full frame — it sees a padded, letterboxed crop of one
person, produced by :func:`prepare_vlm_crop` after YOLO fires. Both latency and
accuracy depend on exactly those crops, so fixtures are generated by running
the real Stage 1 over real clips.

Two things this deliberately does, both learned the hard way:

**It uses the production crop path.** An earlier version called
``crop_detection_focused`` bare, which took that function's *signature*
default of ``dim=0.4`` and never letterboxed — while production dims at
``vlm_focus_dim`` (off by default) and always letterboxes. Every verdict
number measured on those fixtures described a crop the appliance does not
generate. There is now one helper and both callers use it.

**It samples per tracked subject, not per frame.** Keeping the most confident
box in every Nth frame sounds representative and is not: a clip is a handful
of people walking, so consecutive frames of one person are near-duplicates.
Twenty such crops carry the statistical weight of one subject, which makes any
accuracy interval computed over them far too narrow. Sampling by track id and
recording the count in the manifest keeps the real sample size visible.

Usage:
    uv run python bench/make_fixtures.py --video cctv_demo.mp4 --per-track 2
    uv run python bench/make_fixtures.py --video a.mp4 --video b.mp4
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import asdict, dataclass, field
from pathlib import Path

import cv2

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.config.settings import get_settings  # noqa: E402
from app.pipelines.tracker import GreedyIoUTracker  # noqa: E402
from app.pipelines.vlm_worker import (  # noqa: E402
    prepare_vlm_crop,
    subject_pixel_size,
)
from app.schemas.events import BoundingBox  # noqa: E402

MANIFEST_NAME = "manifest.json"


@dataclass
class Fixture:
    """One crop, with enough provenance to trace it back to its source."""

    name: str
    clip: str
    frame_index: int
    track_id: int
    subject_px: int
    width: int
    height: int


@dataclass
class Manifest:
    """The fixture set, plus the numbers that bound what it can prove."""

    fixtures: list[Fixture] = field(default_factory=list)
    clips: list[str] = field(default_factory=list)
    crop_settings: dict = field(default_factory=dict)

    @property
    def subjects(self) -> int:
        """Distinct (clip, track) pairs — the real independent sample size."""
        return len({(f.clip, f.track_id) for f in self.fixtures})


def _tracked_subjects(
    video: Path,
    model,
    tracker: GreedyIoUTracker,
    confidence: float,
    min_subject_px: int,
) -> dict[int, list[tuple[int, BoundingBox, int]]]:
    """Run Stage 1 over one clip and group detections by track id.

    Returns:
        ``{track_id: [(frame_index, bbox, subject_px), ...]}``, only for
        subjects that clear ``min_subject_px`` — the same floor Stage 2
        applies, so the fixtures cannot contain crops production would skip.
    """
    cap = cv2.VideoCapture(str(video))
    if not cap.isOpened():
        raise SystemExit(f"Cannot open {video}")

    by_track: dict[int, list[tuple[int, BoundingBox, int]]] = {}
    frame_index = 0

    while True:
        ok, frame = cap.read()
        if not ok:
            break
        frame_index += 1

        result = model.predict(
            frame, imgsz=640, conf=confidence, classes=[0], verbose=False
        )[0]
        boxes = result.boxes
        if boxes is None or len(boxes) == 0:
            tracker.update([])
            continue

        h, w = frame.shape[:2]
        detections = []
        for row in boxes.data.cpu().numpy():
            detections.append(
                (
                    "person",
                    BoundingBox(
                        x1=float(row[0]) / w,
                        y1=float(row[1]) / h,
                        x2=float(row[2]) / w,
                        y2=float(row[3]) / h,
                    ),
                )
            )

        for track_id, (_label, bbox) in zip(
            tracker.update(detections), detections, strict=True
        ):
            # Longer side, exactly as VLMWorker._too_small measures it, so
            # the fixtures cannot contain crops production would skip.
            box_w, box_h = subject_pixel_size(frame.shape, bbox)
            px = round(max(box_w, box_h))
            if px < min_subject_px:
                continue
            by_track.setdefault(track_id, []).append((frame_index, bbox, px))

    cap.release()
    return by_track


def extract(
    videos: list[Path], out_dir: Path, per_track: int, confidence: float
) -> Manifest:
    """Save up to ``per_track`` crops for every subject in every clip.

    Crops are taken at the subject's largest observed size — the frame where
    there is the most evidence to answer about — and then spread across the
    track, so a long track contributes different moments rather than one burst.
    """
    from ultralytics import YOLO

    settings = get_settings()
    out_dir.mkdir(parents=True, exist_ok=True)
    model = YOLO("models/yolov8n.pt")

    manifest = Manifest(
        clips=[str(v) for v in videos],
        crop_settings={
            "crop_padding": settings.vlm_crop_padding,
            "focus_dim": settings.vlm_focus_dim,
            "square_edge": settings.vlm_square_edge,
            "max_crop_edge": settings.vlm_max_crop_edge,
            "min_subject_px": settings.vlm_min_subject_px,
        },
    )

    for video in videos:
        # A fresh tracker per clip: ids must not carry across unrelated footage.
        by_track = _tracked_subjects(
            video,
            model,
            GreedyIoUTracker(
                iou_threshold=settings.track_iou_threshold,
                max_age_frames=settings.track_max_age_frames,
            ),
            confidence,
            settings.vlm_min_subject_px,
        )

        cap = cv2.VideoCapture(str(video))
        wanted: dict[int, list[tuple[int, BoundingBox, int]]] = {}
        for track_id, seen in by_track.items():
            # Biggest first, then spread over the track's lifetime.
            seen.sort(key=lambda item: -item[2])
            step = max(1, len(seen) // per_track)
            wanted[track_id] = seen[::step][:per_track]

        by_frame: dict[int, list[tuple[int, BoundingBox, int]]] = {}
        for track_id, picks in wanted.items():
            for frame_index, bbox, px in picks:
                by_frame.setdefault(frame_index, []).append((track_id, bbox, px))

        frame_index = 0
        while by_frame:
            ok, frame = cap.read()
            if not ok:
                break
            frame_index += 1
            for track_id, bbox, px in by_frame.pop(frame_index, []):
                crop = prepare_vlm_crop(
                    frame,
                    bbox,
                    crop_padding=settings.vlm_crop_padding,
                    focus_dim=settings.vlm_focus_dim,
                    square_edge=settings.vlm_square_edge,
                    max_crop_edge=settings.vlm_max_crop_edge,
                )
                if crop.size == 0:
                    continue
                name = f"crop_{len(manifest.fixtures):03d}.png"
                cv2.imwrite(str(out_dir / name), crop)
                manifest.fixtures.append(
                    Fixture(
                        name=name,
                        clip=video.name,
                        frame_index=frame_index,
                        track_id=track_id,
                        subject_px=px,
                        width=crop.shape[1],
                        height=crop.shape[0],
                    )
                )
                print(
                    f"  {name}  {crop.shape[1]}x{crop.shape[0]}  "
                    f"{video.name} frame={frame_index} track={track_id} "
                    f"subject={px}px"
                )
        cap.release()

    (out_dir / MANIFEST_NAME).write_text(
        json.dumps(
            {
                "fixtures": [asdict(f) for f in manifest.fixtures],
                "clips": manifest.clips,
                "crop_settings": manifest.crop_settings,
                "subjects": manifest.subjects,
            },
            indent=2,
        )
    )
    return manifest


def main() -> None:
    """CLI entry point."""
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--video",
        type=Path,
        action="append",
        help="Source clip. Repeat for several; more varied footage is the "
        "single biggest lever on how much an accuracy number can be trusted.",
    )
    ap.add_argument("--out", type=Path, default=Path("bench/fixtures"))
    ap.add_argument(
        "--per-track",
        type=int,
        default=2,
        help="Crops per tracked subject. Raising this grows the file count "
        "without growing the independent sample size.",
    )
    ap.add_argument("--confidence", type=float, default=0.30)
    args = ap.parse_args()

    videos = args.video or [Path("cctv_demo.mp4")]
    print(f"Extracting person crops from {len(videos)} clip(s)...")
    manifest = extract(videos, args.out, args.per_track, args.confidence)

    print(
        f"\nWrote {len(manifest.fixtures)} crops from "
        f"{manifest.subjects} distinct subjects to {args.out}"
    )
    if manifest.subjects < 100:
        print(
            f"  NOTE: {manifest.subjects} subjects is a small sample. A "
            "proportion measured here carries roughly "
            f"+/-{100 * 0.98 / max(manifest.subjects, 1) ** 0.5:.0f} points at "
            "95% confidence. Add more varied footage before trusting a "
            "comparison between two close options."
        )


if __name__ == "__main__":
    main()
