"""Extract real Stage 2 inputs from the demo footage.

Benchmarking a VLM on stock photos measures the wrong thing. Stage 2 never
sees a full frame — it sees a padded, context-dimmed crop of one person,
produced by :func:`crop_detection_focused` after YOLO fires. Latency depends
on the aspect ratio and detail of exactly those crops, so the fixtures are
generated by running the real Stage 1 over the real clip.

Run once; the crops are cached as PNGs and reused by every benchmark run so
that repeat runs compare models rather than re-rolling their inputs.

Usage:
    uv run python bench/make_fixtures.py --video cctv_demo.mp4 --count 8
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import cv2

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.pipelines.vlm_worker import crop_detection_focused  # noqa: E402
from app.schemas.events import BoundingBox  # noqa: E402


def extract(video: Path, out_dir: Path, count: int, stride: int) -> list[Path]:
    """Run YOLO over the clip and save the first `count` person crops.

    Args:
        video: Source footage.
        out_dir: Directory to write crops into.
        count: How many crops to keep.
        stride: Sample every Nth frame, so crops come from different moments
            rather than from one contiguous burst of near-identical frames.

    Returns:
        Paths of the written crops.
    """
    from ultralytics import YOLO

    out_dir.mkdir(parents=True, exist_ok=True)
    model = YOLO("models/yolov8n.pt")

    cap = cv2.VideoCapture(str(video))
    if not cap.isOpened():
        raise SystemExit(f"Cannot open {video}")

    written: list[Path] = []
    frame_idx = 0

    while len(written) < count:
        ok, frame = cap.read()
        if not ok:
            break
        frame_idx += 1
        if frame_idx % stride:
            continue

        results = model.predict(frame, imgsz=640, conf=0.35, classes=[0], verbose=False)
        boxes = results[0].boxes
        if boxes is None or len(boxes) == 0:
            continue

        h, w = frame.shape[:2]
        # Largest detection in the frame — the subject a reviewer would look at.
        best = max(boxes, key=lambda b: float(b.conf[0]))
        x1, y1, x2, y2 = (float(v) for v in best.xyxy[0])

        bbox = BoundingBox(x1=x1 / w, y1=y1 / h, x2=x2 / w, y2=y2 / h)
        crop = crop_detection_focused(frame, bbox)
        if crop.size == 0:
            continue

        path = out_dir / f"crop_{len(written):02d}.png"
        cv2.imwrite(str(path), crop)
        written.append(path)
        print(f"  {path.name}  {crop.shape[1]}x{crop.shape[0]}  frame={frame_idx}")

    cap.release()
    return written


def main() -> None:
    """CLI entry point."""
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--video", type=Path, default=Path("cctv_demo.mp4"))
    ap.add_argument("--out", type=Path, default=Path("bench/fixtures"))
    ap.add_argument("--count", type=int, default=8)
    ap.add_argument("--stride", type=int, default=15)
    args = ap.parse_args()

    print(f"Extracting {args.count} person crops from {args.video}...")
    written = extract(args.video, args.out, args.count, args.stride)
    print(f"Wrote {len(written)} crops to {args.out}")


if __name__ == "__main__":
    main()
